-- Liste des communes d'une wilaya, groupées par daïra (pour l'écran de choix)
create view wilaya_communes as
  select w.code as wilaya_code, w.name_ar as wilaya_ar, w.name_fr as wilaya_fr,
         c.daira_ar, c.daira_fr, c.id as commune_id, c.name_ar as commune_ar, c.name_fr as commune_fr
  from communes c join wilayas w on w.code = c.wilaya_code;
grant select on wilaya_communes to anon, authenticated;

-- Nombre de communes par wilaya (affiché à côté de chaque wilaya)
create view wilaya_summary as
  select w.code, w.name_ar, w.name_fr, count(c.id)::int as communes
  from wilayas w left join communes c on c.wilaya_code = w.code
  group by w.code order by w.code;
grant select on wilaya_summary to anon, authenticated;

-- ---------------------------------------------------------------------
-- La commune remplace le champ texte libre
-- ---------------------------------------------------------------------
alter table profiles       add column commune_id smallint references communes (id);
alter table businesses     drop column commune, add column commune_id smallint references communes (id);
alter table listings       drop column commune, add column commune_id smallint references communes (id);
alter table parts_requests add column commune_id smallint references communes (id);
alter table sos_requests   add column commune_id smallint references communes (id);
create index listings_commune on listings (commune_id) where status = 'active';
create index businesses_commune on businesses (commune_id);

-- La commune doit appartenir à la wilaya choisie
create function check_commune_in_wilaya() returns trigger language plpgsql as $$
begin
  if new.commune_id is not null and new.wilaya_code is not null
     and not exists (select 1 from communes where id = new.commune_id and wilaya_code = new.wilaya_code) then
    raise exception 'commune_not_in_wilaya';
  end if;
  return new;
end $$;
create trigger profiles_commune       before insert or update of commune_id, wilaya_code on profiles       for each row execute function check_commune_in_wilaya();
create trigger businesses_commune     before insert or update of commune_id, wilaya_code on businesses     for each row execute function check_commune_in_wilaya();
create trigger listings_commune       before insert or update of commune_id, wilaya_code on listings       for each row execute function check_commune_in_wilaya();
create trigger parts_requests_commune before insert or update of commune_id, wilaya_code on parts_requests for each row execute function check_commune_in_wilaya();
create trigger sos_requests_commune   before insert or update of commune_id, wilaya_code on sos_requests   for each row execute function check_commune_in_wilaya();
